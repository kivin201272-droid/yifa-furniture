# Helper function to crop and save HD studio image
def crop_hd(page_idx, rect, out_path, mask_bottom_pt=0):
    page = doc[page_idx]
    # If mask_bottom_pt is provided, adjust y1
    r = fitz.Rect(rect)
    if mask_bottom_pt > 0:
        r.y1 = r.y1 - mask_bottom_pt
    
    mat = fitz.Matrix(5.0, 5.0)
    pix = page.get_pixmap(matrix=mat, clip=r)
    tmp_path = 'temp_crop.png'
    pix.save(tmp_path)
    
    im = Image.open(tmp_path).convert('RGB')
    
    # Auto-trim near-white borders
    # Find bounding box of non-white pixels (< 248 on RGB)
    bg = Image.new(im.mode, im.size, (255, 255, 255))
    diff = ImageOps.invert(im)
    bbox = diff.getbbox()
    if bbox:
        im = im.crop(bbox)
        
    # Resize to fit within 740x550
    im.thumbnail((740, 550), Image.Resampling.LANCZOS)
    
    # Place on 800x600 pure white canvas
    canvas = Image.new('RGB', (800, 600), (255, 255, 255))
    paste_x = (800 - im.width) // 2
    paste_y = (600 - im.height) // 2
    canvas.paste(im, (paste_x, paste_y))
    
    # Sharpness enhancement
    enhancer = ImageEnhance.Sharpness(canvas)
    canvas = enhancer.enhance(1.3)
    
    canvas.save(out_path, quality=95)
    print(f"Generated HD Image: {out_path} ({im.width}x{im.height} -> 800x600)")

